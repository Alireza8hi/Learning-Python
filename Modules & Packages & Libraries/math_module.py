# math methods that don't need math module
list1 = [3, 6, 34, 12, 14]
x = min(list1)  # new point
y = max(list1)  # new point
z = abs(-12.3)  # new point: قدر مطلق
w = pow(2, 5)  # new point: 2*2*2*2*2
print(x)
print(y)
print(z)
print(w)

# math methods that need math module
import math

print(math.sqrt(81))  # radical
print(math.ceil(2.3))  # increase until next number or method rounds a number upwards to its nearest integer
print(math.ceil(2.7))
print(math.floor(2.3))  # decrease until last number or method rounds a number downwards to its nearest integer
print(math.floor(2.7))
print(math.pi)  # 3.141592653589793 عدد پی
print(math.e)  # 2.718281828459045
print(math.cos(0))  # cos
print(math.sin(0))  # sin
print(math.tan(0))  # tan
print(math.log(100, 10))  # log
print(math.log10(100))  # log base on 10
